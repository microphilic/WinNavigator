int CMainFrame::OnCreate(LPCREATESTRUCT lpCreateStruct)
{
	if (CMDIFrameWndEx::OnCreate(lpCreateStruct) == -1)
		return -1;

	BOOL bNameValid;

	CMDITabInfo mdiTabParams;
	mdiTabParams.m_style = CMFCTabCtrl::STYLE_3D_ONENOTE; // diğer kullanılabilir stiller...
	mdiTabParams.m_bActiveTabCloseButton = TRUE;      // kapat düğmesini sekme alanının sağına yerleştirmek için FALSE olarak ayarlayın
	mdiTabParams.m_bTabIcons = FALSE;    // MDI sekmelerinde belge simgelerini etkinleştirmek için TRUE olarak ayarlayın
	mdiTabParams.m_bAutoColor = TRUE;    // MDI sekmelerinin otomatik renklendirmesini devre dışı bırakmak için FALSE olarak ayarlayın
	mdiTabParams.m_bDocumentMenu = TRUE; // sekme alanının sağ kenarında belge menüsünü etkinleştir
	EnableMDITabbedGroups(TRUE, mdiTabParams);

	if (!m_wndMenuBar.Create(this))
	{
		TRACE0("Menü çubuğu oluşturulamadı\n");
		return -1;      // oluşturulamadı
	}

	m_wndMenuBar.SetPaneStyle(m_wndMenuBar.GetPaneStyle() | CBRS_SIZE_DYNAMIC | CBRS_TOOLTIPS | CBRS_FLYBY);

	// menü çubuğunun, etkinleştirildiğinde odağı almasını engelleyin
	CMFCPopupMenu::SetForceMenuFocus(FALSE);

	if (!m_wndToolBar.CreateEx(this, TBSTYLE_FLAT, WS_CHILD | WS_VISIBLE | CBRS_TOP | CBRS_GRIPPER | CBRS_TOOLTIPS | CBRS_FLYBY | CBRS_SIZE_DYNAMIC) ||
		!m_wndToolBar.LoadToolBar(theApp.m_bHiColorIcons ? IDR_MAINFRAME_256 : IDR_MAINFRAME))
	{
		TRACE0("Araç çubuğu oluşturulamadı\n");
		return -1;      // oluşturulamadı
	}

	CString strToolBarName;
	bNameValid = strToolBarName.LoadString(IDS_TOOLBAR_STANDARD);
	ASSERT(bNameValid);
	m_wndToolBar.SetWindowText(strToolBarName);

	CString strCustomize;
	bNameValid = strCustomize.LoadString(IDS_TOOLBAR_CUSTOMIZE);
	ASSERT(bNameValid);
	m_wndToolBar.EnableCustomizeButton(TRUE, ID_VIEW_CUSTOMIZE, strCustomize);

	// Kullanıcı tanımlı araç çubuğu işlemlerine izin ver:
	InitUserToolbars(nullptr, uiFirstUserToolBarId, uiLastUserToolBarId);

	if (!m_wndStatusBar.Create(this))
	{
		TRACE0("Durum çubuğu oluşturulamadı\n");
		return -1;      // oluşturulamadı
	}
	m_wndStatusBar.SetIndicators(indicators, sizeof(indicators)/sizeof(UINT));

	// TODO: Araç çubuğu ve menü çubuğunun yerleştirilebilir olmasını istemiyorsanız bu beş satırı silin
	m_wndMenuBar.EnableDocking(CBRS_ALIGN_ANY);
	m_wndToolBar.EnableDocking(CBRS_ALIGN_ANY);
	EnableDocking(CBRS_ALIGN_ANY);
	DockPane(&m_wndMenuBar);
	DockPane(&m_wndToolBar);


	// Visual Studio 2005 stili yerleşik pencere davranışını etkinleştir
	CDockingManager::SetDockingMode(DT_SMART);
	// Visual Studio 2005 stili yerleşik pencere otomatik gizleme davranışını etkinleştir
	EnableAutoHidePanes(CBRS_ALIGN_ANY);

	// Gezinti bölmesi solda oluşturulur, bu nedenle sol tarafta yerleştirmeyi geçici olarak devre dışı bırakın:
	EnableDocking(CBRS_ALIGN_TOP | CBRS_ALIGN_BOTTOM | CBRS_ALIGN_RIGHT);

	// "Outlook" gezinti çubuğunu oluştur ve ayarla:
	if (!CreateOutlookBar(m_wndNavigationBar, ID_VIEW_NAVIGATION, m_wndTree, m_wndCalendar, 250))
	{
		TRACE0("Gezinti bölmesi oluşturulamadı\n");
		return -1;      // oluşturulamadı
	}

	// Outlook çubuğu oluşturulur ve sol tarafta yerleştirmeye izin verilmelidir.
	EnableDocking(CBRS_ALIGN_LEFT);
	EnableAutoHidePanes(CBRS_ALIGN_RIGHT);
	// kalıcı değere dayalı olarak görsel yöneticiyi ve stili ayarla
	OnApplicationLook(theApp.m_nAppLook);

	// Gelişmiş pencere yönetimi iletişim kutusunu etkinleştir
	EnableWindowsDialog(ID_WINDOW_MANAGER, ID_WINDOW_MANAGER, TRUE);

	// Araç çubuğu ve yerleşik pencere menüsü değişimini etkinleştir
	EnablePaneMenu(TRUE, ID_VIEW_CUSTOMIZE, strCustomize, ID_VIEW_TOOLBAR);

	// hızlı (Alt+sürükleme) araç çubuğu özelleştirmesini etkinleştir
	CMFCToolBar::EnableQuickCustomization();

	if (CMFCToolBar::GetUserImages() == nullptr)
	{
		// kullanıcı tanımlı araç çubuğu görüntülerini yükle
		if (m_UserImages.Load(_T(".\\UserImages.bmp")))
		{
			CMFCToolBar::SetUserImages(&m_UserImages);
		}
	}

	// menü kişiselleştirmesini etkinleştir (en yakın zamanda kullanılan komutlar)
	// TODO: Her açılan menünün en az bir temel komut içerdiğinden emin olarak kendi temel komutlarınızı tanımlayın.
	CList<UINT, UINT> lstBasicCommands;

	lstBasicCommands.AddTail(ID_FILE_NEW);
	lstBasicCommands.AddTail(ID_FILE_OPEN);
	lstBasicCommands.AddTail(ID_FILE_SAVE);
	lstBasicCommands.AddTail(ID_FILE_PRINT);
	lstBasicCommands.AddTail(ID_APP_EXIT);
	lstBasicCommands.AddTail(ID_EDIT_CUT);
	lstBasicCommands.AddTail(ID_EDIT_PASTE);
	lstBasicCommands.AddTail(ID_EDIT_UNDO);
	lstBasicCommands.AddTail(ID_APP_ABOUT);
	lstBasicCommands.AddTail(ID_VIEW_STATUS_BAR);
	lstBasicCommands.AddTail(ID_VIEW_TOOLBAR);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_OFF_2003);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_VS_2005);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_OFF_2007_BLUE);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_OFF_2007_SILVER);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_OFF_2007_BLACK);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_OFF_2007_AQUA);
	lstBasicCommands.AddTail(ID_VIEW_APPLOOK_WINDOWS_7);

	CMFCToolBar::SetBasicCommands(lstBasicCommands);

	// Pencere başlık çubuğunda belge adının ve uygulama adının sırasını değiştirin. Belge adı,
	// küçük resim ile görünür olduğundan bu, görev çubuğunun kullanışlılığını artırır.
	ModifyStyle(0, FWS_PREFIXTITLE);

	return 0;
}

